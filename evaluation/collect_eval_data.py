"""
================================================================================
VISTAAR RAG Evaluation Pipeline - Context and Response Collector
================================================================================
This script executes the REAL VISTAAR retrieval and answer-generation pipeline
without modifying the backend codebase.

It collects the four mandatory RAGAS evaluation fields for each test question:
  1. user_input: The input question submitted to the system.
  2. reference: The ground-truth reference answer.
  3. retrieved_contexts: The exact list of text chunks retrieved from FAISS (top-k=8).
  4. response: The real answer generated by Gemini under temperature=0.0.

ARCHITECTURAL FINDING (Context Accessibility in Existing Backend):
- The existing HTTP endpoint `POST /ask` returns `{"answer": string}`, omitting
  `retrieved_contexts`.
- The SMALLEST ISOLATED SOLUTION to evaluate RAGAS without mutating `app.py` or
  `qa_service.py` is to import the existing pipeline components (`embeddings.model`,
  `vector_store.search`, and `qa_service.ask_gemini`) directly into this evaluation
  script. This executes the 100% identical pipeline while retaining direct access
  to the retrieved chunk vectors and text.
================================================================================
"""

